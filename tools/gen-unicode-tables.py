"""Generate src/unicode_tables.rs from the running Python's unicodedata.

The Python originals relied on unicodedata / str methods for label cleaning
and digit checks. Generating the tables from the same CPython that the
Python version ran on (nixpkgs python3) keeps the Rust port's answers
identical, Unicode version included.

    nix shell nixpkgs#python3 -c python3 -I tools/gen-unicode-tables.py > src/unicode_tables.rs
"""

import sys
import unicodedata

SPACE = frozenset("\t\n\r\x0b\x0c\x1c\x1d\x1e\x1f\x85  ")
DROP = frozenset(("Cc", "Cf", "Co", "Cs", "Cn", "Zl", "Zp"))


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000 + 1):
        hit = cp <= 0x10FFFF and pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit(name, doc, rs):
    print("/// %s" % doc)
    print("pub static %s: &[(u32, u32)] = &[" % name)
    for a, b in rs:
        print("    (0x%04X, 0x%04X)," % (a, b))
    print("];")
    print()


print("// @generated by tools/gen-unicode-tables.py from Python %s, Unicode %s."
      % (sys.version.split()[0], unicodedata.unidata_version))
print("// Do not edit by hand.")
print()
print('pub const UNICODE_VERSION: &str = "%s";' % unicodedata.unidata_version)
print()
emit("DROP", "General categories Cc Cf Co Cs Cn Zl Zp (clean_label drops these).",
     ranges(lambda cp: unicodedata.category(chr(cp)) in DROP))
emit("SPACE", "Python str.isspace().", ranges(lambda cp: chr(cp).isspace()))
emit("DIGIT", "Python str.isdigit() for one character.", ranges(lambda cp: chr(cp).isdigit()))
emit("DECIMAL", "Python re `\\d` on str (str.isdecimal()).",
     ranges(lambda cp: chr(cp).isdecimal()))
